// Writes deck/foundation-facts.js: the part of the foundation research the deck's opening section shows, as a
// checked-in module. The research itself (facts.json, the stored source pages, the posters) stays in the app repo,
// because this repo is public and deployed; the deck needs only the values and where each one comes from.
//
//   node tools/foundation-facts.mjs            # research at ../../doremimi-superapp/content/doremimi-research
//   node tools/foundation-facts.mjs <folder>   # or name it
//
// Never edit deck/foundation-facts.js by hand: it carries a digest of its own values, and tests/foundation.test.mjs
// checks it, and where the research is at hand compares every value with what snapshot() takes from facts.json today.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

// DOREMIMI_APP names the app repo where it is not beside this one (a worktree, a temp copy), as tests/app-parity does.
export const RESEARCH = process.env.DOREMIMI_APP ? join(process.env.DOREMIMI_APP, 'content/doremimi-research/')
  : fileURLToPath(new URL('../../../doremimi-superapp/content/doremimi-research/', import.meta.url));
const sha = b => createHash('sha256').update(b).digest('hex');
/** The digest FROM carries: the guard recomputes it from the checked-in module to tell a value edited by hand. */
export const digestOf = (FACTS, SOURCES) => sha(JSON.stringify({ FACTS, SOURCES }));

/** What the deck takes from the research folder: { FROM, FACTS, SOURCES }. Exported so the guard runs this very selection. */
export function snapshot(research = RESEARCH) {
const raw = readFileSync(join(research, 'facts.json'));
const facts = JSON.parse(raw);
const register = JSON.parse(readFileSync(join(research, 'sources.json'), 'utf8'));

const only = (o, keys) => Object.fromEntries(keys.map(k => [k, o[k]]));
// No volatile number is taken (channel subscribers, views, video count): the section shows none, and a number that is
// not in the snapshot cannot pass the guard's allow-list.
const NUMBERS = ['books', 'agesConcert', 'siteVideos', 'riddles', 'guestAnswerers'];
const numbers = NUMBERS.map(key => {
  const n = facts.numbers.find(x => x.key === key);
  if (!n) throw new Error(`facts.json has no number "${key}"`);
  if (n.volatile) throw new Error(`"${key}" is volatile; the deck shows it dated or not at all`);
  return only(n, ['key', 'value', 'tr', 'status', 'src']);
});
// The research's own notes ("caveat", "note", "rule") are for whoever writes the copy, not for the deck: left behind.
const FACTS = {
  asOf: facts.asOf,
  // "computed" names the day the site was mirrored, which is the "as of" of every count taken from it.
  statuses: only(facts.statuses, ['computed']),
  foundation: only(facts.foundation, ['nameTr']),
  numbers,
  timeline: facts.timeline.map(t => only(t, ['date', 'tr', 'status', 'src'])),
  concerts: only(facts.concerts, ['titleTr', 'kindTr', 'orchestraTr', 'ages']),
  books: only(facts.books, ['seriesTr', 'author', 'year', 'audienceTr', 'titlesTr']),
  contentLibrary: only(facts.contentLibrary, ['tr']),
  research: { study: only(facts.research.study, ['authors', 'journalTr']) },
};

// Every source id the picked facts cite, plus the two images the section shows, with what the register says of each.
const IMAGES = ['A2', 'A3'];
const cited = new Set([...IMAGES, ...FACTS.numbers.flatMap(n => n.src), ...FACTS.timeline.flatMap(t => t.src), 'S15']);
const entry = id => {
  const f = register.files.find(x => x.id === id);
  if (f) return only(f, ['id', 'url', 'supports', 'fetched', ...(IMAGES.includes(id) ? ['sha256'] : [])]);
  const o = register.other_sources.find(x => x.id === id);
  if (!o) throw new Error(`sources.json has no "${id}"`);
  return only(o, ['id', 'what', 'how', 'supports']);
};
const SOURCES = [...cited].sort((a, b) => a[0].localeCompare(b[0]) || Number(a.slice(1)) - Number(b.slice(1))).map(entry);

let commit = 'unknown';
try { commit = execFileSync('git', ['-C', research, 'log', '-1', '--format=%h %cs', '--', 'facts.json'], { encoding: 'utf8' }).trim() || 'uncommitted'; } catch { /* not a checkout */ }
const FROM = { asOf: facts.asOf, commit, factsSha256: sha(raw), digest: digestOf(FACTS, SOURCES) };
return { FROM, FACTS, SOURCES };
}

// Run as a tool it writes the module; imported (by the guard) it writes nothing.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
const { FROM, FACTS, SOURCES } = snapshot(process.argv[2] ?? RESEARCH);
const out = `/*
 * GENERATED by tools/foundation-facts.mjs from doremimi-superapp/content/doremimi-research (facts.json, sources.json).
 * Do not edit: change the research and run the tool again. FROM.digest is the sha256 of JSON.stringify({ FACTS,
 * SOURCES }), so a guard can tell a value changed here by hand, with or without the research at hand.
 * tests/foundation.test.mjs checks the digest, and the values against facts.json where the research is checked out.
 *
 * Only what the deck's "Dore Mimi, bugüne kadar" section shows or cites is here. The research folder is not copied
 * into this repo (it is public): no stored pages, no posters beyond the two small images in assets/foundation/.
 */
export const FROM = ${JSON.stringify(FROM, null, 2)};

export const FACTS = ${JSON.stringify(FACTS, null, 2)};

export const SOURCES = ${JSON.stringify(SOURCES, null, 2)};
`;
const target = fileURLToPath(new URL('../deck/foundation-facts.js', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${target} (facts as of ${FROM.asOf}, ${FROM.commit})`);
}
